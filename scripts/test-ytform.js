/** v9.6 — 유튜브 송폼 태그 · 나만 보는 악보 (worshipYtForm* · worshipMySheet*) — 시트 · 드라이브 없이 메모리로  ·  node scripts/test-ytform.js */
const sheetsDb = require('../lib/sheetsDb');
const driveStore = require('../lib/driveStore');
const rows = { 유튜브송폼: [], 개인악보: [], 악보저장소: [] };
const live = (t) => (rows[t] = rows[t] || []);
sheetsDb.readAll = async (t) => live(t).map((r, i) => (r ? Object.assign({ __row: i + 2 }, r) : null)).filter(Boolean);
sheetsDb.appendRow = async (t, r) => { live(t).push(Object.assign({}, r)); };
sheetsDb.updateRow = async (t, n, r) => { live(t)[n - 2] = Object.assign({}, r); };
sheetsDb.deleteRow = async (t, n) => { live(t).splice(n - 2, 1); };
let up = 0; const trashed = [];
driveStore.uploadPrivate = async (sub, f) => { up++; return 'https://drive.google.com/uc?export=download&id=DRV' + String(up).padStart(10, '0'); };
driveStore.removeByLink = async (l) => { trashed.push(l); };
const F = require('../routes/live').FNS;
const yt = require('../lib/ytForm');
let pass = 0, fail = 0;
const ok = (c, m, x) => { if (c) { pass++; console.log('  ✓ ' + m); } else { fail++; console.log('  ✗ ' + m + (x !== undefined ? ' → ' + JSON.stringify(x) : '')); } };
const rej = async (p, re, m) => { let e = ''; try { await p; } catch (x) { e = x.message; } ok(re.test(e), m, e); };
(async () => {
  const A = { team: 'T1', name: '김리더', email: 'a@x.com' }, B = { team: 'T1', name: '박팀원', email: 'b@x.com' }, O = { team: 'T2', name: '남', email: 'o@x.com' };
  const VID = 'dQw4w9WgXcQ', ROOM = '2026-10-11';
  console.log('■ 송폼 태그');
  let g = await F.worshipYtFormGet(B, VID);
  ok(g.tags.length === 0 && g.at === 0, '처음엔 비어 있음');
  await rej(F.worshipYtFormGet(B, 'bad'), /유튜브 영상/, '영상 ID 확인');
  const s = await F.worshipYtFormSave(B, VID, 'Way Maker', [{ t: 45.04, k: 'C' }, { t: 12.33, k: 'V1' }, { t: 0, k: 'Intro' }, { t: 12.33, k: 'V1' }, { t: -2, k: 'x' }], 0);
  ok(JSON.stringify(s.tags) === JSON.stringify([{ t: 0, k: 'Intro' }, { t: 12.3, k: 'V1' }, { t: 45, k: 'C' }]) && s.by === '박팀원', '팀원 누구나 저장 · 정리', s);
  g = await F.worshipYtFormGet(A, VID);
  ok(g.tags.length === 3 && g.by === '박팀원' && g.title === 'Way Maker', '같은 팀 다른 사람에게 보임');
  ok((await F.worshipYtFormGet(O, VID)).tags.length === 0, '다른 팀은 따로');
  await rej(F.worshipYtFormSave(A, VID, '', [{ t: 1, k: 'V1' }], 0), /방금 이 영상/, '그사이 저장된 것은 덮어쓰지 않음');
  const s2 = await F.worshipYtFormSave(A, VID, '', [{ t: 1, k: 'V1' }], g.at + 0);
  ok(s2.by === '김리더' && rows.유튜브송폼.length === 1 && rows.유튜브송폼[0]['제목'] === 'Way Maker', '최신에서 고치면 저장 (한 줄 · 제목 유지)');
  await F.worshipYtFormSave(A, VID, '', [], s2.at);
  ok(rows.유튜브송폼.length === 0, '모두 지우면 줄도 지움');
  ok(yt.cleanTags(Array.from({ length: 100 }, (_, i) => ({ t: i, k: 'C' }))).length === 80, '80개까지');
  console.log('■ 나만 보는 악보');
  const PDF = 'data:application/pdf;base64,' + Buffer.from('%PDF-1.4 x').toString('base64');
  const a = await F.worshipMySheetAdd(B, ROOM, '내 악보.pdf', PDF);
  ok(a.sheet && a.sheet.mine && a.sheet.name === '내 악보' && a.sheet.id === 'DRV0000000001', '올리기 (드라이브 링크 공유 없이)', a);
  ok((await F.worshipMySheets(B, ROOM)).sheets.length === 1, '내 목록 1개');
  ok((await F.worshipMySheets(A, ROOM)).sheets.length === 0, '같은 팀 다른 사람에게는 안 보임');
  ok((await F.worshipMySheets(B, '2026-10-18')).sheets.length === 0, '다른 예배에는 안 보임');
  await rej(F.worshipMySheetAdd(B, ROOM, 'a.txt', 'data:text/plain;base64,QUJD'), /PDF 또는 사진/, 'PDF · 사진만');
  await rej(F.worshipMySheetAdd(B, 'nope', 'a.pdf', PDF), /예배/, '방 확인');
  const ctxB = { teams: ['T1'], member: { '이메일': 'b@x.com', '이름': '박팀원' } }, ctxA = { teams: ['T1'], member: { '이메일': 'a@x.com', '이름': '김리더' } };
  ok(!!(await yt.mineRowFor(ctxB, 'DRV0000000001')), '/sheet/<id> — 본인은 열 수 있음');
  ok(!(await yt.mineRowFor(ctxA, 'DRV0000000001')), '/sheet/<id> — 다른 사람은 못 엶');
  await rej(F.worshipMySheetDel(A, ROOM, 'DRV0000000001'), /내가 올린/, '남의 것은 못 지움');
  const d = await F.worshipMySheetDel(B, ROOM, 'DRV0000000001');
  ok(d.sheets.length === 0 && trashed.length === 1, '내 것 지우기 (드라이브 파일도)');
  const src = require('fs').readFileSync(require('path').join(__dirname, '..', 'routes', 'live.js'), 'utf8');
  ok(/worship\/ytform\.js/.test(src) && /mineRowFor/.test(src), '라이브 악보 화면 · 파일 열기 연결');
  console.log(fail ? '✗ 실패 ' + fail : '✓ 모두 통과 (통과 ' + pass + ')'); process.exit(fail ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(1); });
