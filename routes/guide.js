/** 그림 + 번호 설명 */
function fig(file, alt, legend) {
  return `<figure class="gd-fig"><a href="/guide-img/${file}.jpg" target="_blank" rel="noopener"><img src="/guide-img/${file}.jpg" alt="${alt}" loading="lazy" decoding="async"></a>
    ${legend && legend.length ? `<ol class="gd-legend">${legend.map((t) => `<li>${t}</li>`).join('')}</ol>` : ''}
    <figcaption>그림을 누르면 크게 열려요</figcaption></figure>`;
}
const tip = (t) => `<p class="gd-tip"><b>팁</b> ${t}</p>`;
const warn = (t) => `<p class="gd-warn"><b>주의</b> ${t}</p>`;
function sec(id, no, title, lead, body, who) {
  return `<section class="ph-card gd-sec" id="${id}"><div class="gd-h"><span class="gd-no">${no}</span><h2>${title}</h2>${who ? `<span class="gd-who">${who}</span>` : ''}</div>${lead ? `<p class="gd-lead">${lead}</p>` : ''}${body}</section>`;
}

